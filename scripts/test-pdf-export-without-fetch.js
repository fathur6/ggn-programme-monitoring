const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const server = fs.readFileSync(path.join(root, 'gas', 'Code.js'), 'utf8');
const design = fs.readFileSync(path.join(root, 'gas', 'PdfDesign.js'), 'utf8');

// The document starts as a copy of an A4 portrait template, is filled with the
// Slides service and exported to PDF through DriveApp.
assert.match(design, /PDF_TEMPLATE_ID_ = '1[A-Za-z0-9_-]{20,}'/);
assert.match(design, /DriveApp\.getFileById\(PDF_TEMPLATE_ID_\)\.makeCopy/);
assert.match(design, /SlidesApp\.openById/);
assert.match(design, /DriveApp\.getFileById\(presentationId\)/);
assert.match(design, /getAs\(MimeType\.PDF\)/);
assert.match(design, /setTrashed\(true\)/);
assert.match(design, /ROUND_RECTANGLE/);

// A missing template still produces a document.
assert.match(design, /\|\| SlidesApp\.create\(deckTitle\)/);

// The document must identify its generator, timestamp and filename.
assert.match(design, /'Generated by '/);
assert.match(design, /filename \+ '\.pdf/);

// Both logos are placed, UniSZA first, without any server-side fetch.
assert.match(design, /pdfLogo_\(slide, 'unisza'/);
assert.match(design, /pdfLogo_\(slide, 'gs'/);
assert.match(design, /insertImage\(url\)/);
assert.doesNotMatch(design, /UrlFetchApp/);

// The programme detail still drives the PDF columns.
assert.match(server, /buildProgrammePdfBlob_\(programme, detail, code, meta \|\| \{\}\)/);

// The Slides permission must be declared; the project lists scopes explicitly.
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'gas', 'appsscript.json'), 'utf8'));
assert.ok(
  manifest.oauthScopes.indexOf('https://www.googleapis.com/auth/presentations') !== -1,
  'presentations scope must be declared'
);

console.log('PDF export uses the A4 template design with logos.');
