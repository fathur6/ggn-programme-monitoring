const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const server = fs.readFileSync(path.join(root, 'gas', 'Code.js'), 'utf8');
const design = fs.readFileSync(path.join(root, 'gas', 'PdfDesign.js'), 'utf8');

// The document is laid out as an A4 portrait deck so it can use rounded cards,
// then exported to PDF with DriveApp.
assert.match(design, /SlidesApp\.create\(/);
assert.match(design, /setPageWidth\(PDF_L_\.w\)/);
assert.match(design, /DriveApp\.getFileById\(presentationId\)/);
assert.match(design, /getAs\(MimeType\.PDF\)/);
assert.match(design, /setTrashed\(true\)/);
assert.match(design, /ROUNDED_RECTANGLE/);

// The generated document must identify its generator, timestamp and filename.
assert.match(design, /'Generated by '/);
assert.match(design, /filename \+ '\.pdf/);
assert.match(design, /generatedAt/);

// Both logos are placed, UniSZA first.
assert.match(design, /pdfLogo_\(slide, 'unisza'/);
assert.match(design, /pdfLogo_\(slide, 'gs'/);

// Logos are downloaded once and cached in Drive.
assert.match(design, /logo-'\s*\+\s*key\s*\+\s*'\.png'/);

// The programme detail still drives SDG/SC columns.
assert.match(server, /buildProgrammePdfBlob_\(programme, detail, code, meta \|\| \{\}\)/);

console.log('PDF export uses the Slides design with cached logos.');
